from database import db
from datetime import datetime

class Prediction(db.Model):
    """
    Stores ML model predictions for projects.
    Predictions are generated by the ML service and stored separately from project data.
    """
    __tablename__ = 'predictions'

    prediction_id = db.Column(db.Integer, primary_key=True, autoincrement=True)
    project_id = db.Column(db.String(50), db.ForeignKey('projects.project_id'), nullable=False)
    
    # ML prediction results
    delay_probability = db.Column(db.Float, nullable=True)  # 0.0 to 1.0 probability
    prediction_confidence = db.Column(db.Float, nullable=True)  # Optional confidence score
    
    # Risk classification (derived from probability)
    risk_level = db.Column(db.String(50), nullable=True)  # HIGH, MEDIUM, LOW, NO_RISK, UNKNOWN
    risk_color = db.Column(db.String(20), nullable=True)  # RED, ORANGE, YELLOW, GREEN, GREY
    
    # Metadata
    model_version = db.Column(db.String(50), nullable=True)  # Version of ML model used
    prediction_date = db.Column(db.DateTime, default=datetime.utcnow, nullable=False)
    
    # Optional: Store contributing factors as JSON string for explainability
    # (detailed in recommendations table)
    
    def __repr__(self):
        return f'<Prediction {self.project_id}: {self.risk_level} ({self.delay_probability:.2f})>'
    
    def to_dict(self):
        """Convert model to dictionary for JSON serialization"""
        return {
            'prediction_id': self.prediction_id,
            'project_id': self.project_id,
            'delay_probability': float(self.delay_probability) if self.delay_probability is not None else None,
            'prediction_confidence': float(self.prediction_confidence) if self.prediction_confidence else None,
            'risk_level': self.risk_level,
            'risk_color': self.risk_color,
            'model_version': self.model_version,
            'prediction_date': self.prediction_date.isoformat() if self.prediction_date else None,
        }
